def test_12_strict_json():
    """Test 12: Strict JSON validation"""
    try:
        # Send request with unknown field
        payload = {
            "html": "<html><body>Test</body></html>",
            "validation_level": "standard",
            "unknown_field": "should_be_rejected"
        }
        
        resp = requests.post(f"{BASE_URL}/validate", headers=HEADERS, json=payload, timeout=5)
        
        # Should return 422 (Validation Error)
        if resp.status_code == 422:
            log_test(12, "Strict JSON", True, "Unknown fields rejected (422)")
            return
        
        # If 200, check if field was silently ignored (bad)
        if resp.status_code == 200:
            log_test(12, "Strict JSON", False, "Unknown field accepted (should reject)")
            return
        
        log_test(12, "Strict JSON", False, f"Unexpected status: {resp.status_code}")
    
    except Exception as e:
        log_test(12, "Strict JSON", False, str(e))

