def test_10_export_base64():
    """Test 10: Export HTML (base64)"""
    try:
        html = "<html><body>Base64 Test</body></html>"
        
        payload = {
            "html": html,
            "filename": "test_base64.html",
            "format": "base64"
        }
        
        resp = requests.post(f"{BASE_URL}/export", headers=HEADERS, json=payload, timeout=5)
        
        if resp.status_code != 200:
            log_test(10, "Export Base64", False, f"Status {resp.status_code}")
            return
        
        data = resp.json()
        
        if not data.get("success"):
            log_test(10, "Export Base64", False, f"Export failed: {data.get('message')}")
            return
        
        b64_data = data.get("base64_data")
        if not b64_data:
            log_test(10, "Export Base64", False, "Missing base64_data")
            return
        
        # Verify can decode
        try:
            decoded = base64.b64decode(b64_data).decode("utf-8")
            if "Base64 Test" not in decoded:
                log_test(10, "Export Base64", False, "Decoded content mismatch")
                return
        except Exception as e:
            log_test(10, "Export Base64", False, f"Decode error: {e}")
            return
        
        log_test(10, "Export Base64", True, f"Base64 length: {len(b64_data)} chars")
    
    except Exception as e:
        log_test(10, "Export Base64", False, str(e))

