def log_test(test_num: int, test_name: str, passed: bool, details: str = ""):
    """Test-Ergebnis loggen"""
    global passed_tests, failed_tests
    
    status = "✓" if passed else "✗"
    color = "\033[0;32m" if passed else "\033[0;31m"
    reset = "\033[0m"
    
    if passed:
        passed_tests += 1
    else:
        failed_tests += 1
    
    print(f"{color}[{status}] Test {test_num} ({test_name}): {'PASS' if passed else 'FAIL'}{reset}{f' - {details}' if details else ''}")

def test_1_health():
    """Test 1: Health Check"""
    try:
        resp = requests.get(f"{BASE_URL}/health", timeout=5)
        
        if resp.status_code != 200:
            log_test(1, "Health", False, f"Status {resp.status_code}")
            return
        
        data = resp.json()
        
        # Check response structure
        required_keys = ["status", "service", "kuerzel", "port", "uptime_seconds", "templates_available", "jinja2_support"]
        missing = [k for k in required_keys if k not in data]
        
        if missing:
            log_test(1, "Health", False, f"Missing keys: {missing}")
            return
        
        # Validate values
        if data["status"] != "ok":
            log_test(1, "Health", False, f"Status not ok: {data['status']}")
            return
        
        if data["kuerzel"] != "htmlp":
            log_test(1, "Health", False, f"Wrong kürzel: {data['kuerzel']}")
            return
        
        if data["port"] != 12360:
            log_test(1, "Health", False, f"Wrong port: {data['port']}")
            return
        
        uptime = data["uptime_seconds"]
        templates = data["templates_available"]
        
        log_test(1, "Health", True, f"Uptime: {uptime:.2f}s, Templates: {templates}, Jinja2: {data['jinja2_support']}")
    
    except Exception as e:
        log_test(1, "Health", False, str(e))

