set -euo pipefail

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Project root
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# Config files
ENV_FILE="${ROOT}/.env.current"
CONFIG_FILE="${ROOT}/.system_mode_config"
AUDIT_LOG="${ROOT}/logs/system_mode_audit.log"

###############################################################################
# Utility Functions
###############################################################################

log_info() {
    echo -e "${BLUE}[INFO]${NC} $*" | tee -a "$AUDIT_LOG"
}

log_success() {
    echo -e "${GREEN}[✓]${NC} $*" | tee -a "$AUDIT_LOG"
}

log_warn() {
    echo -e "${YELLOW}[⚠]${NC} $*" | tee -a "$AUDIT_LOG"
}

log_error() {
    echo -e "${RED}[✗]${NC} $*" | tee -a "$AUDIT_LOG" >&2
}

audit_log() {
    local event=$1
    local detail=${2:-}
    local timestamp=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
    echo "{\"timestamp\":\"$timestamp\",\"event\":\"$event\",\"detail\":\"$detail\",\"user\":\"$USER\"}" >> "$AUDIT_LOG"
}

###############################################################################
# Configuration Management
###############################################################################

load_current_mode() {
    if [ -f "$ENV_FILE" ]; then
        source "$ENV_FILE"
        echo "${ELION_ENV:-development}"
    else
        echo "development"
    fi
}

save_mode_config() {
    local mode=$1
    cat > "$ENV_FILE" << EOF
# Auto-generated by system_mode_switch.sh
# DO NOT EDIT MANUALLY
ELION_ENV=$mode
SYSTEM_MODE_SWITCHED_AT=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
SYSTEM_MODE_SWITCHED_BY=$USER
EOF
    chmod 600 "$ENV_FILE"
}

get_mode_config() {
    local mode=$1
    case "$mode" in
        development)
            cat << 'EOF'
{
  "env": "development",
  "enable_owner_override": true,
  "enable_admin_bypass": true,
  "enable_emergency_command": true,
  "token_storage": "plaintext",
  "require_ui_auth": false,
  "require_https": false,
  "log_level": "DEBUG",
  "ports": {
    "dashboard": 12349,
    "bridge": 12351,
    "opena1": 12344,
    "opena2": 12345,
    "kordp": 12346
  }
}
EOF
            ;;
        staging)
            cat << 'EOF'
{
  "env": "staging",
  "enable_owner_override": false,
  "enable_admin_bypass": false,
  "enable_emergency_command": true,
  "token_storage": "vault",
  "require_ui_auth": true,
  "require_https": true,
  "log_level": "INFO",
  "ports": {
    "dashboard": 12349,
    "bridge": 12351,
    "openwebui": 8080
  }
}
EOF
            ;;
        production)
            cat << 'EOF'
{
  "env": "production",
  "enable_owner_override": false,
  "enable_admin_bypass": false,
  "enable_emergency_command": true,
  "token_storage": "aws_secrets",
  "require_ui_auth": true,
  "require_https": true,
  "log_level": "WARNING",
  "ports": {
    "dashboard": 12349,
    "bridge": 12351,
    "nginx": 443
  }
}
EOF
            ;;
        *)
            log_error "Unknown mode: $mode"
            return 1
            ;;
    esac
}

###############################################################################
# Validation
###############################################################################

validate_mode() {
    local mode=$1
    case "$mode" in
        development|staging|production)
            return 0
            ;;
        *)
            return 1
            ;;
    esac
}

validate_environment() {
    local target_env=$1
    
    log_info "Validating $target_env environment..."
    
    # Check Python environment
    if ! command -v python3 &> /dev/null; then
        log_error "Python3 not found"
        return 1
    fi
    
    # Check required files
    local required_files=(
        "19.dashboard_agent/main_dashboard.py"
        "19.dashboard_agent/config.py"
        "19.dashboard_agent/security.py"
    )
    
    for file in "${required_files[@]}"; do
        if [ ! -f "$file" ]; then
            log_error "Required file missing: $file"
            return 1
        fi
    done
    
    # Check ports availability (for non-production)
    if [ "$target_env" != "production" ]; then
        check_ports_available
    fi
    
    # Environment-specific checks
    case "$target_env" in
        development)
            check_dev_environment
            ;;
        staging)
            check_staging_environment
            ;;
        production)
            check_production_environment
            ;;
    esac
    
    log_success "Environment validation passed"
    return 0
}

check_dev_environment() {
    log_info "Checking DEV environment requirements..."
    
    # Check .env.development
    if [ ! -f ".env.development" ]; then
        log_warn "Missing .env.development – creating template"
        create_env_template "development"
    fi
    
    # Check venv
    if [ ! -d "1.portier_openai/venv313" ]; then
        log_warn "Virtual environment not found – you may need to run: bash 1.portier_openai/setup_venv313.sh"
    fi
}

check_staging_environment() {
    log_info "Checking STAGING environment requirements..."
    
    # Check Vault connectivity
    if ! command -v vault &> /dev/null; then
        log_warn "HashiCorp Vault CLI not found – install with: brew install hashicorp/tap/vault"
    fi
    
    # Check VAULT_ADDR
    if [ -z "${VAULT_ADDR:-}" ]; then
        log_error "VAULT_ADDR not set – required for STAGING"
        return 1
    fi
}

check_production_environment() {
    log_info "Checking PRODUCTION environment requirements..."
    
    # Check AWS CLI
    if ! command -v aws &> /dev/null; then
        log_error "AWS CLI not found – required for PRODUCTION"
        return 1
    fi
    
    # Check AWS credentials
    if ! aws sts get-caller-identity &> /dev/null; then
        log_error "AWS credentials not configured"
        return 1
    fi
    
    # Check required AWS resources
    if [ -z "${AWS_SECRETS_ARN:-}" ]; then
        log_error "AWS_SECRETS_ARN not set"
        return 1
    fi
    
    # Verify TLS certificates
    if [ ! -f "certs/certificate.pem" ] || [ ! -f "certs/private_key.pem" ]; then
        log_error "TLS certificates not found in certs/"
        return 1
    fi
    
    log_success "PRODUCTION environment ready"
}

check_ports_available() {
    local ports=(12349 12351 12344 12345 12346 8080)
    
    for port in "${ports[@]}"; do
        if lsof -Pi :$port -sTCP:LISTEN -t >/dev/null 2>&1; then
            log_warn "Port $port already in use"
        fi
    done
}

create_env_template() {
    local env=$1
    local template_file=".env.$env"
    
    log_info "Creating $template_file template"
    
    case "$env" in
        development)
            cat > "$template_file" << 'EOF'
# Development Environment Template
ELION_ENV=development
OWNER_TOKEN=dev-owner-secret-12345
ADMIN_TOKEN=dev-admin-token-12345
DASHBOARD_TOKEN=dev-dashboard-token-12345
REQUIRE_UI_AUTH=false
REQUIRE_HTTPS=false
LOG_LEVEL=DEBUG
EOF
            ;;
        staging)
            cat > "$template_file" << 'EOF'
# Staging Environment Template
ELION_ENV=staging
VAULT_ADDR=http://127.0.0.1:8200
VAULT_TOKEN=<set-your-token>
REQUIRE_UI_AUTH=true
REQUIRE_HTTPS=true
LOG_LEVEL=INFO
EOF
            ;;
        production)
            cat > "$template_file" << 'EOF'
# Production Environment Template
ELION_ENV=production
AWS_REGION=eu-central-1
AWS_SECRETS_ARN=arn:aws:secretsmanager:eu-central-1:ACCOUNT:secret:elion-prod
REQUIRE_UI_AUTH=true
REQUIRE_HTTPS=true
LOG_LEVEL=WARNING
EOF
            ;;
    esac
    
    chmod 600 "$template_file"
    log_success "Template created: $template_file"
}

###############################################################################
# Mode Switching
###############################################################################

show_current_mode() {
    local current_mode=$(load_current_mode)
    local config=$(get_mode_config "$current_mode")
    
    echo ""
    echo -e "${BLUE}╔════════════════════════════════════════╗${NC}"
    echo -e "${BLUE}║      ELION System Mode Status          ║${NC}"
    echo -e "${BLUE}╚════════════════════════════════════════╝${NC}"
    echo ""
    echo -e "Current Mode: ${GREEN}$current_mode${NC}"
    echo ""
    echo "Configuration:"
    echo "$config" | python3 -m json.tool 2>/dev/null || echo "$config"
    echo ""
    
    # Show active services
    show_active_services
}

show_active_services() {
    echo "Active Services:"
    local services=(
        "12349:dashboard"
        "12351:bridge"
        "12344:opena1"
        "12345:opena2"
        "12346:kordp"
    )
    
    for service in "${services[@]}"; do
        local port=${service%%:*}
        local name=${service##*:}
        if lsof -Pi :$port -sTCP:LISTEN -t >/dev/null 2>&1; then
            echo -e "  ✅ $name (port $port)"
        else
            echo -e "  ❌ $name (port $port)"
        fi
    done
}

switch_mode() {
    local target_mode=$1
    local current_mode=$(load_current_mode)
    
    if [ "$current_mode" = "$target_mode" ]; then
        log_warn "Already in $target_mode mode"
        return 0
    fi
    
    log_info "Switching from $current_mode → $target_mode"
    
    # Validate target
    if ! validate_mode "$target_mode"; then
        log_error "Invalid mode: $target_mode"
        return 1
    fi
    
    # Validate environment
    if ! validate_environment "$target_mode"; then
        log_error "Environment validation failed"
        return 1
    fi
    
    # Safety check: Ask for confirmation
    if [ "$target_mode" = "production" ]; then
        echo -e "${YELLOW}⚠️  WARNING: You are about to switch to PRODUCTION mode${NC}"
        echo -e "This will:"
        echo -e "  - Disable all Owner Bypasses"
        echo -e "  - Enable HTTPS requirement"
        echo -e "  - Enforce strong authentication"
        echo -e "  - Enable audit logging"
        echo ""
        read -p "Type 'yes' to confirm: " confirm
        if [ "$confirm" != "yes" ]; then
            log_warn "Switch to PRODUCTION cancelled"
            return 1
        fi
    fi
    
    # Stop running services
    log_info "Stopping running services..."
    if [ -f "bin/ops.sh" ]; then
        bash bin/ops.sh stop 2>/dev/null || log_warn "Could not stop services"
    fi
    
    # Save new mode
    save_mode_config "$target_mode"
    
    # Export new environment
    export ELION_ENV="$target_mode"
    
    # Create environment file
    if [ ! -f ".env.$target_mode" ]; then
        create_env_template "$target_mode"
    fi
    
    # Log mode switch
    audit_log "mode_switch" "from $current_mode to $target_mode"
    
    log_success "Successfully switched to $target_mode mode"
    log_info "Environment saved to .env.current"
    
    # Show next steps
    show_next_steps "$target_mode"
}

show_next_steps() {
    local mode=$1
    
    echo ""
    echo "Next steps:"
    echo ""
    
    case "$mode" in
        development)
            echo "1. Load environment: source .env.$mode"
            echo "2. Start services: bin/ops.sh start"
            echo "3. Verify: bin/ops.sh verify"
            ;;
        staging)
            echo "1. Ensure Vault is running: vault server -dev"
            echo "2. Load environment: source .env.$mode"
            echo "3. Start with Docker: docker-compose -f docker-compose.staging.yml up"
            ;;
        production)
            echo "1. Verify AWS credentials: aws sts get-caller-identity"
            echo "2. Load environment: source .env.$mode"
            echo "3. Deploy with: docker-compose -f docker-compose.prod.yml up -d"
            echo "4. Monitor: docker-compose -f docker-compose.prod.yml logs -f"
            ;;
    esac
    
    echo ""
}

###############################################################################
# Main Command Router
###############################################################################

main() {
    # Ensure logs directory exists
    mkdir -p "$(dirname "$AUDIT_LOG")"
    
    local command=${1:-show}
    
    case "$command" in
        show)
            show_current_mode
            ;;
        switch)
            if [ $# -lt 2 ]; then
                log_error "Usage: $0 switch <dev|staging|prod>"
                return 1
            fi
            switch_mode "$2"
            ;;
        validate)
            if [ $# -lt 2 ]; then
                log_error "Usage: $0 validate <dev|staging|prod>"
                return 1
            fi
            validate_environment "$2"
            ;;
        help|--help|-h)
            cat << 'EOF'
ELION System Mode Switch – Task 01

Usage:
  system_mode_switch.sh show                # Show current mode + config
  system_mode_switch.sh switch <ENV>        # Switch to development/staging/production
  system_mode_switch.sh validate <ENV>      # Validate target environment
  system_mode_switch.sh help                # Show this help

Environments:
  development   – DEV mode (Bypasses enabled, local only)
  staging       – STAGING (Vault-based, partial restrictions)
  production    – PROD (All bypasses disabled, strict security)

Examples:
  system_mode_switch.sh show
  system_mode_switch.sh switch development
  system_mode_switch.sh validate production

Audit Log:
  logs/system_mode_audit.log
EOF
            ;;
        *)
            log_error "Unknown command: $command"
            log_info "Try: $0 help"
            return 1
            ;;
    esac
}

# Execute main
main "$@"

